/**
 * UI text, in the two languages the product ships.
 *
 * `en` is the source of truth and `zh` is typed as the same shape, so a key
 * added to one and forgotten in the other is a `tsc --noEmit` failure rather
 * than an English word appearing mid-sentence in a Chinese UI. That is the
 * whole reason this is a typed object instead of a lookup by string key.
 *
 * Anything with a number or a name in it is a function, so the two languages
 * can put the pieces in different orders — template concatenation at the call
 * site cannot be translated.
 *
 * Not translated on purpose: log event kinds (`tool_call`, `request_begin`),
 * config field names (`base_url`, `max_tokens`), approval mode ids and profile
 * names. Those are identifiers the user also types and greps for.
 */

