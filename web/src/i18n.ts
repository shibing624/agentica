const TABLES: Record<Lang, Strings> = { en, zh };

export function readStoredLang(): Lang {
  return localStorage.getItem("ag_lang") === "zh" ? "zh" : "en";
}

/** For module-level code (toasts, confirm dialogs) that has no hooks. */
export function getStrings(): Strings {
  return TABLES[getState().lang];
}

/** For components: re-renders when the language changes. */
export function useStrings(): Strings {
  return TABLES[useAppState().lang];
}

/** `lang` on <html> so the browser hyphenates and picks fonts correctly, and so
 *  a screen reader announces the right language. */
export function applyLang(lang: Lang) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
}

export function setLang(lang: Lang) {
  localStorage.setItem("ag_lang", lang);
  applyLang(lang);
  setState({ lang });
  pushPrefs();
}
